OX_OPTIONS = ["⭕ 맞아요", "❌ 아니에요"]


def render(items, qtype):
    out = []
    for item in items:
        if qtype == "ox":
            qid, prompt, hint, answer, explain = item
            options = OX_OPTIONS
        else:
            qid, prompt, hint, options, answer, explain = item
        opts = "\n".join(f'      {json.dumps(o, ensure_ascii=False)},' for o in options)
        out.append(
            "  {\n"
            f'    id: {json.dumps(qid)},\n'
            f'    type: "{qtype}",\n'
            f"    prompt: {json.dumps(prompt, ensure_ascii=False)},\n"
            f"    hint: {json.dumps(hint, ensure_ascii=False)},\n"
            "    options: [\n"
            f"{opts}\n"
            "    ],\n"
            f"    answer: {answer},\n"
            f"    explain: {json.dumps(explain, ensure_ascii=False)},\n"
            "  },"
        )
    return "\n".join(out)


def insert(src, name, block):
    header = f"const {name}: Question[] = [\n"
    start = src.index(header) + len(header)
    end = src.index("\n];", start)
    body = src[start:end]
    if not body.rstrip().endswith(","):
        body = body.rstrip() + ","
    return src[:start] + body.rstrip("\n") + "\n" + block + src[end:]


