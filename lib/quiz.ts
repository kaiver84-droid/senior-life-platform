function hashStr(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** 오늘의 공식 퀴즈 문제 수 — 2026-11-19 사용자 요청으로 3 → 5문제 */
export const DAILY_QUIZ_COUNT = 5;

/**
 * 그날의 5문제 — 날짜가 같으면 항상 같다.
 * 1번은 초성, 2번은 옛날 노래로 고정하고, 3~5번은 나머지 여섯 주제(틀린 그림·OX·넌센스·
 * 추억·보이스피싱·제철)를 날짜에 따라 돌아가며 하나씩 낸다. 그래서 하루만 풀어도 서로 다른
 * 유형 5가지를 만나고, 며칠 지나면 여덟 주제가 모두 고루 나온다.
 */
const DAILY_ROTATING_POOLS: Question[][] = [SPOT, OX, NONSENSE, NOSTALGIA, SAFETY_SLANG, SEASONAL];

export function dailyQuestions(date: string): Question[] {
  const c = CHOSEONG[hashStr(date + "|ch") % CHOSEONG.length];
  const l = LYRICS[hashStr(date + "|ly") % LYRICS.length];
  const start = hashStr(date + "|third") % DAILY_ROTATING_POOLS.length;
  const picked: Question[] = [];
  for (let i = 0; i < DAILY_QUIZ_COUNT - 2; i++) {
    const pool = DAILY_ROTATING_POOLS[(start + i) % DAILY_ROTATING_POOLS.length];
    picked.push(pool[hashStr(date + "|r" + i + "|" + pool.length) % pool.length]);
  }
  return [c, l, ...picked];
}

function pickRandom(pool: Question[], avoid: Set<string>): Question {
  const candidates = pool.filter((q) => !avoid.has(q.id));
  const list = candidates.length > 0 ? candidates : pool;
  return list[Math.floor(Math.random() * list.length)];
}

/**
 * 연습 모드용 3문제.
 * - `only` 를 주면 그 주제에서 3문제를 고른다(‘주제 골라 풀기’).
 * - 주지 않으면 서로 다른 유형 5가지 중 무작위 3가지를 골라 하나씩 낸다.
 * 점수는 연습 화면에서 맞힌 문제마다 1점씩 따로 더해지고(하루 미션 점수와는 별개),
 * excludeIds 에 방금 푼 문제 id 를 넣으면 같은 문제가 바로 다시 나오지 않는다.
 */
export function practiceQuestions(excludeIds: string[] = [], only?: QuizType): Question[] {
  const avoid = new Set(excludeIds);
  if (only) {
    const pool = QUIZ_POOLS[only];
    const used = new Set(avoid);
    const picked: Question[] = [];
    for (let i = 0; i < Math.min(3, pool.length); i++) {
      const rest = pool.filter((q) => !used.has(q.id));
      const q = pickRandom(rest.length ? rest : pool, used);
      picked.push(q);
      used.add(q.id);
    }
    return picked;
  }
  const shuffled = [...QUIZ_TYPE_ORDER].sort(() => Math.random() - 0.5).slice(0, 3);
  return shuffled.map((t) => pickRandom(QUIZ_POOLS[t], avoid));
}

/** 문제 순서를 섞는다(Fisher–Yates) — 누를 때마다 다른 순서로 나오게 */
export function shuffleQuestions<T>(list: T[]): T[] {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/**
 * ‘주제 골라 바로 풀기’ 무한 연습용 문제 순환기.
 * - 주제를 주면 그 주제 풀을(초성 75 · 노래 82 · 그림 32 · OX 74 · 넌센스 55 ·
 *   추억 38 · 보이스피싱 38 · 제철 39),
 *   주지 않으면 전체 433문항을 섞어 순서대로 낸다.
 * - 같은 문제가 바로 연달아 나오지 않고, 풀을 다 쓰면 다시 섞어 끝없이 이어 간다.
 */
export function createEndlessQueue(only?: QuizType): () => Question {
  const base = only ? QUIZ_POOLS[only] : ALL_QUESTIONS;
  let deck: Question[] = [];
  let last: Question | null = null;
  return () => {
    if (deck.length === 0) {
      deck = shuffleQuestions(base);
      // 다시 섞은 맨 앞이 방금 푼 문제면 뒤쪽 문제와 자리를 바꿔 연달아 나오지 않게 한다
      if (last && deck.length > 1 && deck[0].id === last.id) {
        const swap = 1 + Math.floor(Math.random() * (deck.length - 1));
        [deck[0], deck[swap]] = [deck[swap], deck[0]];
      }
    }
    last = deck.shift() as Question;
    return last;
  };
}

export function calcPoints(correct: number, total: number, seconds: number): number {
  const base = correct * 10;
  const perfect = correct === total && total > 0 ? 20 : 0;
  const speed = seconds < 90 ? 10 : seconds < 180 ? 5 : 0;
  return base + perfect + speed;
}
